"""Export only the public names, aliases and platform IDs from the app's directory."""
import ast
import json
from pathlib import Path
import re

site = Path(__file__).resolve().parents[1]
source = (site.parent / "src/resources/web/app.js").read_text()
directory = source.split("const schools=[\n", 1)[1].split("\n];", 1)[0]
quoted = r"""('(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*")"""
rows = []
for line in directory.splitlines():
    match = re.fullmatch(r"\s*\{n:" + quoted + ",s:" + quoted + ",u:" + quoted +
                         ",a:" + quoted + r"\},?\s*", line)
    if not match:
        raise ValueError(f"Unrecognized school entry: {line}")
    name, platform, _, aliases = map(ast.literal_eval, match.groups())
    if platform not in ("moodle", "canvas", "brightspace", "omnivox"):
        raise ValueError(f"Unknown platform: {platform}")
    rows.append(json.dumps([name, platform, aliases], ensure_ascii=False))
(site / "assets/schools.js").write_text(
    "// Generated by maintenance/sync-schools.py\nconst schoolDirectory = [\n"
    + ",\n".join(rows) + "\n];\n")
print(f"{len(rows)} schools")
